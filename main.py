# 1. Подключаем нужные инструменты
# Path помогает составлять пути к файлам.
from pathlib import Path

# pandas — библиотека для работы с таблицами.
# «as pd» задаёт короткое имя: дальше пишем pd вместо pandas.
import pandas as pd

# Эта функция делит таблицу на обучающую и тестовую выборки.
# Библиотека устанавливается как scikit-learn, а в коде называется sklearn.
from sklearn.model_selection import train_test_split

# 2. Загружаем исходные данные
# __file__ — путь к выполняемому main.py.
# resolve() получает абсолютный путь, parent — папку этого файла.
# Оператор / добавляет к пути имя train.csv: это не деление чисел.
file_path = Path(__file__).resolve().parent / "train.csv"

# read_csv читает CSV и создаёт DataFrame — таблицу pandas.
# df — выбранное нами имя переменной, в которой хранится эта таблица.
df = pd.read_csv(file_path)

# 3. Знакомимся с таблицей и считаем пропуски
# print выводит текст или результат вычисления в окно Run.
# head() берёт первые пять строк, а to_string() показывает их без
# сокращения списка столбцов. Сама таблица df при этом не меняется.
print("Первые пять строк датасета:")
print(df.head().to_string())

# shape возвращает пару чисел: (количество строк, количество столбцов).
# Символы \n в строке означают переход на новую строку для удобства чтения.
print("\nКоличество строк и столбцов:")
print(df.shape)

# isnull() проверяет каждую ячейку: True — пропуск, False — значение есть.
# sum() складывает True как единицы отдельно для каждого столбца.
# Получаем количество пропущенных значений по столбцам.
print("\nКоличество пропущенных значений в исходной таблице:")
print(df.isnull().sum())

# 4. Выбираем столбцы для дальнейшей обработки
# Для этого простого варианта работы не используем имена и идентификаторы
# пассажиров как признаки модели. Из них можно получать дополнительные
# признаки, например группу пассажиров, но здесь мы этого не делаем.
# drop создаёт таблицу без указанных столбцов; исходная df сохраняется.
data = df.drop(columns=["Name", "PassengerId"])
# Transported — целевой столбец: результат, который будущая модель
# должна предсказывать. Пропусков в нём нет. Его не заполняем,
# не нормализуем и в дальнейшем не используем как входной признак.

# 5. Разделяем данные ДО вычисления значений для заполнения пропусков
# Обучающая выборка нужна для настройки обработки и будущего обучения.
# Тестовая — для последующей проверки на отложенных данных.
# test_size=0.3: примерно 30% строк идут в тест, остальные — в обучение.
# random_state=42: фиксируем случайное перемешивание, чтобы повторные
# запуски на одном файле давали одинаковое разбиение. Число 42 условное.
# stratify сохраняет примерно одинаковую долю True/False в Transported
# в обеих выборках. Функция возвращает сразу две таблицы.
train_df, test_df = train_test_split(
    data,
    test_size=0.3,
    random_state=42,
    stratify=data["Transported"]
)

# Создаём явные отдельные копии, которые дальше будем изменять.
train_df = train_df.copy()
test_df = test_df.copy()
# Покажем пропуски в каждой выборке до заполнения — так можно сравнить
# результат обработки с исходным состоянием именно этих выборок.
print("\nПропуски ДО заполнения — обучающая выборка:")
print(train_df.isnull().sum())
print("\nПропуски ДО заполнения — тестовая выборка:")
print(test_df.isnull().sum())

# 6. Перечисляем числовые и категориальные признаки
# Квадратные скобки здесь создают список названий столбцов.
# Age — возраст, остальные числовые столбцы — расходы на услуги.
numeric_columns = [
    "Age", "RoomService", "FoodCourt",
    "ShoppingMall", "Spa", "VRDeck"
]
# Категориальные признаки описывают принадлежность к категории:
# планету, криосон, каюту, пункт назначения и VIP-статус.
# Номер каюты Cabin пока оставляем текстом. Его преобразование — позже.
categorical_columns = [
    "HomePlanet", "CryoSleep", "Cabin", "Destination", "VIP"
]

# 7. Заполняем числовые пропуски медианами
# Цикл for повторяет действия для каждого названия из списка.
# train_df[column] выбирает один столбец по текущему названию column.
# Медиана — центральное значение отсортированного ряда; при чётном
# количестве значений это среднее двух центральных. Пропуски игнорируются.
# Она менее чувствительна к редким очень большим расходам, чем среднее.
for column in numeric_columns:
    median_value = train_df[column].median()

    # fillna заменяет только пропуски, сохраняя имеющиеся значения.
    # Результат присваиваем обратно столбцу с помощью знака =.
    train_df[column] = train_df[column].fillna(median_value)

    # Для теста используем ТО ЖЕ значение из обучающей выборки.
    # Если считать медиану по тесту, его данные будут влиять на обработку:
    # это называется утечкой данных и мешает независимой проверке модели.
    test_df[column] = test_df[column].fillna(median_value)

    print(f"Числовой столбец {column}: медиана = {median_value}")

# 8. Заполняем категориальные пропуски модами
# Мода — самое частое значение столбца. mode() может вернуть несколько
# значений при одинаковой частоте; iloc[0] выбирает первое из них.
# В этом датасете в каждом из перечисленных столбцов есть известные
# значения, поэтому результат mode() не будет пустым.
for column in categorical_columns:
    mode_value = train_df[column].mode().iloc[0]

    # Снова считаем замену только по обучению и применяем к обеим выборкам.
    # Для Cabin это простое учебное заполнение самой частой каютой;
    # оно не восстанавливает фактическую каюту конкретного пассажира.
    train_df[column] = train_df[column].fillna(mode_value)
    test_df[column] = test_df[column].fillna(mode_value)

    # Буква f перед строкой позволяет подставлять значения переменных
    # в места, обозначенные фигурными скобками.
    print(f"Категориальный столбец {column}: мода = {mode_value}")

# 9. Проверяем результат
# Во всех столбцах обеих выборок после заполнения должны быть нули.
print("\nПропуски ПОСЛЕ заполнения — обучающая выборка:")
print(train_df.isnull().sum())
print("\nПропуски ПОСЛЕ заполнения — тестовая выборка:")
print(test_df.isnull().sum())

# Строки при заполнении не удалялись. Два столбца мы исключили ранее,
# поэтому ожидаются размеры (6085, 12) и (2608, 12).
print("\nРазмер обучающей выборки:", train_df.shape)
print("Размер тестовой выборки:", test_df.shape)

# Двойной sum() сначала считает пропуски по столбцам, затем их общий итог.
print("\nВсего пропусков в обучающей выборке:",
      train_df.isnull().sum().sum())
print("Всего пропусков в тестовой выборке:",
      test_df.isnull().sum().sum())

# 10. Нормализуем числовые признаки
# Подключаем инструмент масштабирования из scikit-learn.
from sklearn.preprocessing import MinMaxScaler

# Создаём объект, который будет хранить минимумы и максимумы
# каждого числового столбца обучающей выборки.
scaler = MinMaxScaler()

# Сохраняем несколько строк до преобразования для сравнения.
# copy() создаёт отдельную копию, которая не изменится при нормализации.
before_scaling = train_df[numeric_columns].head().copy()

# fit_transform выполняет два действия:
# 1. Находит минимум и максимум каждого столбца обучающей выборки.
# 2. Пересчитывает значения по формуле:
#    новое значение = (значение - минимум) / (максимум - минимум).
#
# В обучающей выборке значения окажутся в диапазоне от 0 до 1.
# Двойные квадратные скобки здесь не нужны: numeric_columns уже список.
train_df[numeric_columns] = scaler.fit_transform(
    train_df[numeric_columns]
)

# Тестовую выборку преобразуем по минимумам и максимумам,
# найденным на обучающей. Повторно обучать scaler на тесте нельзя.
# Если тестовое значение выходит за пределы обучающего диапазона,
# его результат может оказаться меньше 0 или больше 1 — это допустимо.
test_df[numeric_columns] = scaler.transform(
    test_df[numeric_columns]
)

print("\nПервые пять строк числовых признаков ДО нормализации:")
print(before_scaling.to_string())

print("\nТе же строки ПОСЛЕ нормализации:")
print(train_df[numeric_columns].head().to_string())

# Проверяем минимум и максимум каждого обработанного столбца.
# agg() применяет перечисленные операции к каждому столбцу.
print("\nМинимумы и максимумы обучающей выборки:")
print(train_df[numeric_columns].agg(["min", "max"]))
# Transported и категориальные столбцы не нормализуем.

# 11. Выделяем из номера каюты палубу и борт
# Обрабатываем обе выборки одинаковым способом.
# Цикл поочерёдно записывает в переменную table каждую таблицу.
for table in [train_df, test_df]:

    # str.split("/") разделяет текст по символу /.
    # Например, "B/0/P" превращается в список ["B", "0", "P"].
    cabin_parts = table["Cabin"].str.split("/")

    # str[0] берёт первый элемент — обозначение палубы.
    table["Deck"] = cabin_parts.str[0]

    # str[2] берёт третий элемент — обозначение борта.
    table["Side"] = cabin_parts.str[2]

# Полный номер каюты больше не используем.
# Это упрощение для лабораторной: номер каюты может содержать
# полезную информацию, но здесь оставляем только палубу и борт.
train_df = train_df.drop(columns=["Cabin"])
test_df = test_df.drop(columns=["Cabin"])

# 12. Преобразуем логические значения в числа
# В этих столбцах находятся значения True и False.
# astype(int) заменяет True на 1, а False на 0.
# Transported остаётся целевым столбцом, который будем предсказывать.
boolean_columns = ["CryoSleep", "VIP", "Transported"]

for column in boolean_columns:
    train_df[column] = train_df[column].astype(int)
    test_df[column] = test_df[column].astype(int)

# 13. Кодируем текстовые категории методом one-hot encoding
# Нельзя просто присвоить планетам числа 1, 2, 3:
# это создало бы искусственный порядок между категориями.
#
# Вместо этого создаём отдельный столбец для каждой категории.
# Например, HomePlanet_Earth:
# 1 — пассажир с Земли, 0 — пассажир с другой планеты.
columns_to_encode = ["HomePlanet", "Destination", "Deck", "Side"]

# get_dummies создаёт новую таблицу с закодированными категориями.
# dtype=int задаёт числовые значения 0 и 1 в новых столбцах.
# Остальные столбцы, включая нормализованные числа, сохраняются.
train_encoded = pd.get_dummies(
    train_df,
    columns=columns_to_encode,
    dtype=int
)

test_encoded = pd.get_dummies(
    test_df,
    columns=columns_to_encode,
    dtype=int
)

# Набор и порядок столбцов определяем по обучающей выборке.
# reindex приводит тестовую таблицу к этой же структуре:
# — добавляет отсутствующие столбцы и заполняет их нулями;
# — исключает столбцы категорий, которых не было в обучении;
# — устанавливает одинаковый порядок столбцов.
#
# Если в тесте встретится неизвестная категория, все индикаторы
# соответствующего признака для этой строки будут равны нулю.
test_encoded = test_encoded.reindex(
    columns=train_encoded.columns,
    fill_value=0
)

print("\nПервые пять строк после кодирования категорий:")
print(train_encoded.head().to_string())

print("\nРазмеры таблиц после кодирования:")
print("Обучающая:", train_encoded.shape)
print("Тестовая:", test_encoded.shape)

print("\nОдинаковые столбцы в обеих таблицах:")
print(train_encoded.columns.equals(test_encoded.columns))

print("\nВсего пропусков после кодирования:")
print("Обучающая:", train_encoded.isnull().sum().sum())
print("Тестовая:", test_encoded.isnull().sum().sum())

# 14. Сохраняем обработанные таблицы в CSV
# Сохраняем файлы рядом с main.py.
output_folder = Path(__file__).resolve().parent

# index=False запрещает записывать служебные номера строк pandas
# в дополнительный столбец CSV.
# Исходный train.csv не изменяется.
train_encoded.to_csv(
    output_folder / "train_processed.csv",
    index=False
)

test_encoded.to_csv(
    output_folder / "test_processed.csv",
    index=False
)

# Повторный запуск перезапишет эти два обработанных файла.
print("\nОбработанные данные сохранены:")
print(output_folder / "train_processed.csv")
print(output_folder / "test_processed.csv")